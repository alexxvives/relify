export function advisorGreeting(firstName: string, now = new Date()): string {
  const hour = Number(
    new Intl.DateTimeFormat("en-GB", {
      hour: "numeric",
      hourCycle: "h23",
      timeZone: "Europe/Madrid",
    }).format(now),
  );
  const hello = hour < 12 ? advisorCopy.morning : hour < 20 ? advisorCopy.afternoon : advisorCopy.evening;

  return `${hello}, ${firstName}`;
}
