export function documentCountLabel(count: number): string {
  return count === 1 ? "1 documento" : `${count} documentos`;
}

export function upcomingMeetingsTitle(count: number): string {
  return count === 1 ? "Tienes 1 próxima reunión" : `Tienes ${count} próximas reuniones`;
}

export function pendingActionsTitle(count: number): string {
  if (count === 1) {
    return "Tienes 1 acción pendiente";
  }

  return `Tienes ${count} acciones pendientes`;
}

export function threadMessageCount(count: number): string {
  if (count === 1) {
    return "1 mensaje";
  }

  return `${count} mensajes`;
}

export function sellerGreeting(displayName: string, now = new Date()): string {
  const hour = Number(
    new Intl.DateTimeFormat("en-GB", {
      hour: "2-digit",
      hourCycle: "h23",
      timeZone: "Europe/Madrid",
    }).format(now),
  );
  const hello = hour < 14 ? "Buenos días" : hour < 21 ? "Buenas tardes" : "Buenas noches";
  const first = displayName.trim().split(/\s+/)[0] ?? displayName;
  return `${hello}, ${first}`;
}
